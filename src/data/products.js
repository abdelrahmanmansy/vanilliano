export function getProductById(id) {
  return products.find((product) => product.id === id)
}

export function getProductsByCategory(categoryId) {
  return products.filter((product) => product.category === categoryId)
}

export function getRelatedProducts(product, limit = 4) {
  return products
    .filter((p) => p.category === product.category && p.id !== product.id)
    .slice(0, limit)
}

export function getBestSellers(limit = 8) {
  return products
    .filter((product) => product.badge === 'bestseller')
    .concat(products.filter((p) => p.badge !== 'bestseller').sort((a, b) => b.rating - a.rating))
    .slice(0, limit)
}

export function getOnSale(limit = 8) {
  return products
    .filter((product) => product.discount > 0)
    .sort((a, b) => b.discount - a.discount)
    .slice(0, limit)
}

export function getNewArrivals(limit = 8) {
  return products
    .filter((product) => product.badge === 'new')
    .concat(products.filter((p) => p.badge !== 'new'))
    .slice(0, limit)
}